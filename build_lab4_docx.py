# Helper to add image paragraph + caption paragraph
def add_figure(doc, img_name, caption_text, width_inches=5.8):
    img_path = os.path.join(screens_dir, img_name)
    if not os.path.exists(img_path):
        print(f'Warning: {img_path} not found!')
        return
    p_img = doc.add_paragraph()
    p_img.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run_img = p_img.add_run()
    run_img.add_picture(img_path, width=Inches(width_inches))

    p_cap = doc.add_paragraph(style='Caption')
    p_cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p_cap.add_run(caption_text)

